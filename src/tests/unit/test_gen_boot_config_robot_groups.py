def test_group_functions_share_fail_closed_require_call_sites():
    """The new default*Group() functions read the SAME _require() call
    sites as the pre-existing functions -- unchanged fail-closed
    strictness (the ticket's own acceptance criterion): deleting a key one
    of the new functions depends on (planner.v_max, read by both
    planner_config_for_config() -> defaultPlannerLimits() AND
    defaultPlannerGroup()) still raises MissingRobotConfigKeyError from
    generate(), the same as it always has."""
    cfg = _tovez_cfg()
    del cfg["planner"]["v_max"]

    with pytest.raises(gbc.MissingRobotConfigKeyError) as exc_info:
        gbc.generate(cfg, "data/robots/tovez.json")

    assert exc_info.value.key_path == "planner.v_max"


