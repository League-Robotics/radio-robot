"""src/tests/unit/test_gen_boot_config_robot_groups.py -- generator-level
proof for ticket 132-005 (sprint 132 "configuration discipline": retarget
baking -- populate Config::Robot defaults from today's JSON shape).

scripts/gen_boot_config.py gains seven new no-argument
``default*Group()`` functions -- one per ``msg::ConfigGroupTarget``
(Geometry/Motors/Drive/WheelControl/Planner/Otos/Estimator,
src/firm/messages/robot_config.h, generated by ticket 002 from
src/protos/robot_config.proto) -- each reading the SAME ``_require()``/
``_get()`` call sites the pre-existing ``default*Config()``/
``default*BootConfig()`` functions already use (unchanged JSON path,
unchanged fail-closed strictness), but writing into the NEW generated
``msg::Geometry``/``msg::Motors``/``msg::Drive``/``msg::WheelControl``/
``msg::Planner``/``msg::Otos``/``msg::Estimator`` group structs instead of
the old hand-declared boot_config.h ones.

This is ADDITIVE for this ticket, not a replacement -- see
gen_boot_config.py's own module docstring ("132-005") for why: the
pre-existing functions still have live callers (boot_wiring.cpp/
boot_calibration.cpp/main.cpp), so this file also asserts they are still
emitted, unchanged, alongside the seven new ones.

Mirrors src/tests/unit/test_gen_boot_config_otos.py's/
test_gen_boot_config_planner.py's own in-process pattern (invokes the
generator module directly against the real data/robots/tovez.json) rather
than compiling firmware -- gen_boot_config.py's C++ output is a pure
function of (robot JSON, generator code), so proving the generator's
STRING output carries the right literal values is equivalent to proving
the compiled default*Group() function bodies do, and HOST_BUILD compiling
the regenerated boot_config.cpp is verified separately (`just build-sim`).

Collected under src/tests/unit/ (a generator/tooling-level check, not
sim/bench/playfield-scoped -- see tests/CLAUDE.md); pyproject.toml's
testpaths includes tests/unit.
"""

import json
import sys
from pathlib import Path

import pytest

# src/tests/unit/test_gen_boot_config_robot_groups.py -> unit -> tests -> repo root
_REPO_ROOT = Path(__file__).resolve().parents[3]
_SCRIPTS_DIR = _REPO_ROOT / "src" / "scripts"
_TOVEZ_JSON = _REPO_ROOT / "data" / "robots" / "tovez.json"

if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

import gen_boot_config as gbc  # noqa: E402  (path must be set up before this import)


def _tovez_cfg() -> dict:
    return json.loads(_TOVEZ_JSON.read_text())


def test_generate_emits_all_seven_group_functions_additively():
    """generate()'s output gains all seven Config::Robot group-default
    functions without disturbing any pre-existing default*Config()/
    default*BootConfig() function (still called by boot_wiring.cpp/
    boot_calibration.cpp/main.cpp today -- deleting them would break
    HOST_BUILD, out of this ticket's scope)."""
    content = gbc.generate(_tovez_cfg(), "data/robots/tovez.json")

    # Additive: every pre-existing generated function is still emitted.
    assert "void defaultMotorConfigs(msg::MotorConfig* out)" in content
    assert "msg::DrivetrainConfig defaultDrivetrainConfig()" in content
    assert "OtosBootConfig defaultOtosBootConfig()" in content
    assert "EstimatorBootConfig defaultEstimatorConfig()" in content
    assert "ShaperBootConfig defaultShaperConfig()" in content
    assert "DriveBootConfig defaultDriveConfig()" in content
    assert "WheelControllerBootConfig defaultWheelControllerConfig()" in content
    assert "PlannerBootConfig defaultPlannerLimits()" in content

    # New (132-005): one function per msg::ConfigGroupTarget.
    assert "msg::Geometry defaultGeometryGroup()" in content
    assert "msg::Motors defaultMotorsGroup()" in content
    assert "msg::Drive defaultDriveGroup()" in content
    assert "msg::WheelControl defaultWheelControlGroup()" in content
    assert "msg::Planner defaultPlannerGroup()" in content
    assert "msg::Otos defaultOtosGroup()" in content
    assert "msg::Estimator defaultEstimatorGroup()" in content


def test_default_geometry_group_matches_tovez_json():
    """Geometry: geometry.trackwidth, calibration.rotational_slip/
    rotation_gain_pos/rotation_offset_deg -- a representative sample of
    trackwidth_for_config()/rotational_slip_for_config()/
    rotation_calibration_for_config()'s own real tovez.json values."""
    content = gbc.generate(_tovez_cfg(), "data/robots/tovez.json")

