def test_default_planner_group_matches_tovez_json():
    """Planner: the BOOT-ONLY planner.* surface -- v_max/omega_max/
    control_period/actuation_delay/settle_*/heading_hold_gain/
    decel_plan_fraction. The six shaper-ceiling fields (a_max/a_decel/
    alpha_max/alpha_decel/jerk_max/yaw_jerk_max) are SPLIT OUT, 132-017
    (JSON reshape ticket, stakeholder-sanctioned mid-sprint scope
    addition) -- see test_default_planner_shaper_group_matches_tovez_json()
    below. The formerly-DEAD shaper_* (prefixed) fields (robot_config.
    proto's own header checklist) are separately DELETED, 132-015 (schema
    fields now `reserved`, C++ struct/generator function gone -- see that
    message's own trailing comment and config/boot_config.h's note at
    ShaperBootConfig's former declaration site) -- NOT the same fields as
    this split, see PlannerShaper's own header comment for the
    distinction."""
    cfg = _tovez_cfg()
    content = gbc.generate(cfg, "data/robots/tovez.json")

    assert "cfg.v_max = 400.0f;" in content
    # control_period/actuation_delay are read FROM tovez.json rather than
    # frozen as literals here. Both are "= Core::RobotLoop::kCycle" by
    # construction (see robot_loop.h's kCycle doc comment), so they move
    # every time the loop period does -- they were 40, then 50, and became
    # 32 on 2026-08-07, and a hardcoded literal turns each of those
    # legitimate changes into a spurious generator failure. This is the fix
    # clasi/issues/later/B-gen-boot-config-parity-tests-encode-superseded-
    # literals.md proposes for this whole family: assert the generator
    # faithfully emits what the JSON says, which is the property this test
    # actually defends.
    assert f"cfg.control_period = {gbc._f(cfg['planner']['control_period'])};" in content
    assert f"cfg.actuation_delay = {gbc._f(cfg['planner']['actuation_delay'])};" in content
    # Derived from the JSON, not pinned to a literal -- this assertion used to
    # hard-code 0.0f (130-011's zeroed gain), which contradicted this test's
    # own stated property two comments up ("the generator faithfully emits what
    # the JSON says") and turned a deliberate re-tune into a test failure. The
    # value moved 0.0 -> 1.0 on 2026-08-13 when heading hold was re-enabled on
    # the OTOS; see tovez.json's planner._settle_note for why 130-011's
    # zeroing rationale no longer applies.
    assert f"cfg.heading_hold_gain = {gbc._f(cfg['planner']['heading_hold_gain'])};" in content
    assert "cfg.decel_plan_fraction = 0.4f;" in content
    # 134-003 terminal fine-align. align_tol is RADIANS -- 0.017453 rad is
    # the bench report's 1.0 DEGREE operating point, converted once in
    # tovez.json. A value near 1.0 here would mean degrees leaked into a
    # radian field (57x), which no downstream check would notice.
    assert "cfg.align_tol = 0.017453f;" in content
    assert "cfg.align_max_nudges = 6;" in content
    # DELETED, 132-015 -- confirm they stay gone.
    assert "shaper_a_max" not in content
    assert "shaper_yaw_jerk_max" not in content
    # SPLIT OUT, 132-017 -- defaultPlannerGroup()'s own output must not
    # carry the shaper-ceiling fields any more (they moved to
    # defaultPlannerShaperGroup(), checked separately below); scoped to
    # this one function's own generated body, not the whole file (the
    # sibling defaultPlannerShaperGroup() legitimately DOES emit
    # "cfg.a_max = ...").
    planner_group_start = content.index("msg::Planner defaultPlannerGroup()")
    planner_group_end = content.index("msg::PlannerShaper defaultPlannerShaperGroup()")
    planner_group_body = content[planner_group_start:planner_group_end]
    assert "cfg.a_max" not in planner_group_body
    assert "cfg.yaw_jerk_max" not in planner_group_body


