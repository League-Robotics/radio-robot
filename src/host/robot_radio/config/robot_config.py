# ---------------------------------------------------------------------------
# Host-only groups -- 1:1 identical to their robot_config_generated.py
# counterpart (Identity/Connection/Vision), so no hand-written subclass is
# needed here. Plain aliases, kept for backward-compatible imports --
# NOT a "hand-written BaseModel class": no field is re-declared, this is a
