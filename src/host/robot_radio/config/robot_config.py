# ---------------------------------------------------------------------------
# Host-only sections with NO generated counterpart. robot_config.proto
# excludes these entirely (its own header comment: every key under
# wheels/encoders/gripper/peripherals is "read by no firmware code" --
# "stay in the file under the one-file rule but never cross the wire").
# Stay hand-declared for that reason; this module's own derived
# mm_per_tick computation is wheels/encoders' one real consumer.
#
# 132-016: extra='forbid' here too -- these sections are as much a part of
# "an unrecognized key in a robot JSON fails loudly" as the generated
# groups; excluding them from the generator's own schema (dead to
# firmware) is not a reason to let a typo inside them vanish silently.
# ---------------------------------------------------------------------------

class OffsetXY(BaseModel):
    model_config = ConfigDict(extra="forbid")

    x: float = 0.0
    y: float = 0.0


class WheelsConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    wheel_diameter_mm: Optional[float] = None
    ticks_per_rev: Optional[float] = None
    ticks_per_mm: Optional[float] = None


class EncodersConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    has_encoders: bool = False
    encoder_count: int = 0


class GripperConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    has_gripper: bool = False
    gripper_offset_mm: Optional[OffsetXY] = None


class PeripheralsConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # Digital port (J1..J4) the line laser is wired to. None = no laser
    # wired (fail-closed default -- a robot that doesn't set this explicitly
    # in its data/robots/*.json should not silently assume port 4 is wired).
    laser_port: Optional[int] = None


# ---------------------------------------------------------------------------
# Geometry -- a thin hand-written extension of the generated group: every
# generated field (trackwidth/rotational_slip/rotation_gain_pos/
# rotation_offset/rotation_gain_neg/rotation_offset_neg) is inherited
# unchanged; only otos_untrusted and the rotational_slip domain validator
# are hand-added here.
# ---------------------------------------------------------------------------

class GeometryConfig(Geometry):
    """``robot_config_generated.Geometry`` plus the one field and the one
    validator the generated shape does not carry.

    ``otos_untrusted`` -- ``robot_config.proto`` deliberately excludes this
    field (its own header comment: "none is read by any _require()/_get()
    call in gen_boot_config.py today ... dead data"), but that audit only
    checked FIRMWARE consumers. ``robot_radio.planner.heading.
    HeadingCorrector`` reads ``geometry.otos_untrusted`` HOST-side (via
    ``getattr(geometry, "otos_untrusted", False)``) to choose encoder-
    derived pose over raw OTOS pose for a rig whose chip is mechanically
    decoupled from the wheels (see that module's own docstring, and
    ``clasi/issues/rig-persistent-otos-distrust.md``). Dropping the field
    here would not raise -- ``getattr``'s own fallback swallows it -- it
    would silently flip both ``tovez.json``/``tovez_nocal.json`` back to
    trusting OTOS, exactly the "silent no-op" class of bug this sprint
    exists to eliminate. Kept here, at the SAME JSON path
    (``geometry.otos_untrusted``) it already occupied, pending a decision
    on whether it belongs in the generated schema (flagged, not silently
    reconciled -- see ticket 132-020's own completion report for the
    follow-up).

    ``model_config`` is INHERITED from ``Geometry`` (``extra="forbid"``,
    132-016) -- pydantic v2 merges a subclass's own ``model_config`` with
    every base's, so a plain, unconfigured subclass keeps the parent's
    settings without redeclaring them (confirmed empirically). Restated
    explicitly below anyway, for the same reason every other group in this
    file states it explicitly: a reader scanning this file for "does this
    forbid extra keys" should not have to check the generated module too.
    """
    model_config = ConfigDict(extra="forbid")

    otos_untrusted: bool = False

    @field_validator("rotational_slip")
    @classmethod
    def _validate_rotational_slip_domain(cls, v: float) -> float:
        """Domain {0} u [0.5, 1.0], non-contiguous -- 0 is the uncalibrated
        sentinel (``effectiveTrackWidth()``'s own "0 == uncalibrated
        sentinel" contract), not a divide-by-zero. No (min)/(max)/
        (abs_max) proto option pair can express a non-contiguous domain --
        robot_config.proto's own header comment names this exact "thin
        hand-written validation layer around the generated pydantic model"
        as this check's home.
        """
        if v != 0.0 and not (0.5 <= v <= 1.0):
            raise ValueError(
                f"rotational_slip must be 0 (uncalibrated sentinel) or in "
                f"[0.5, 1.0]; got {v}"
            )
        return v


