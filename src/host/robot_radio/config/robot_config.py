class RobotConfig(BaseModel):
    """The whole robot JSON, one field per top-level section.

    ``extra="forbid"`` (132-016) catches an unrecognized TOP-LEVEL section
    name too, not just an unrecognized key inside a known one -- e.g. the
    OLD-shape file's own ``calibration``/``control`` sections (no matching
    field here at all as of ticket 020's grouped-shape rewiring) now raise
    at this level, before pydantic even descends into a sub-group's own
    ``extra="forbid"``.
    """
    model_config = ConfigDict(extra="forbid")

    schema_version: int = 1

    # -- robot_config.proto's groups (132-020, +navigator 135-004) ----------
    identity: IdentityConfig
    connection: ConnectionConfig = ConnectionConfig()
    vision: VisionConfig = VisionConfig()
    geometry: GeometryConfig = GeometryConfig()
    motors: Motors = Motors()
    drive: Drive = Drive()
    wheel_control: WheelControl = WheelControl()
    planner: Planner = Planner()
    # planner_shaper (132-017): split out of Planner, stakeholder-sanctioned
    # mid-sprint scope addition -- the six shaper-ceiling fields
    # (a_max/a_decel/alpha_max/alpha_decel/jerk_max/yaw_jerk_max) now carry
    # their own ConfigGroupTarget (PLANNER_SHAPER, LIVE) because they have
    # their own re-appliable setter (Motion::Planner::applyShaperLimits()),
    # unlike the rest of Planner. See robot_config.proto's PlannerShaper
    # message header comment for the full rationale.
    planner_shaper: PlannerShaper = PlannerShaper()
    otos: Otos = Otos()
    estimator: Estimator = Estimator()
    # navigator (135-004): Motion::NavigatorLimits' own group (robot_config.
    # proto's Navigator message) -- LIVE, sourced through the same
    # Configurator::install(NAVIGATOR)/applyGroup()/applyField() path every
    # other live group already uses.
    navigator: Navigator = Navigator()

    # -- host-only sections with no generated counterpart --------------------
    wheels: WheelsConfig = WheelsConfig()
    encoders: EncodersConfig = EncodersConfig()
    gripper: GripperConfig = GripperConfig()
    peripherals: PeripheralsConfig = PeripheralsConfig()

    # Derived field — not stored in JSON, computed after load
    mm_per_tick: Optional[float] = None

    @model_validator(mode="before")
    @classmethod
    def _strip_underscore_documentation_keys(cls, data):
        """Strip every leading-underscore key, recursively, from the raw
        JSON dict BEFORE pydantic validates it (132-017, JSON reshape).

        Established project convention (pre-dating this ticket, e.g.
        tovez.json's own ``_otos_linear_scale_note``/``_rotational_slip_
        note``/``_vel_gains_domain``): a leading-underscore key anywhere in
        a robot JSON is documentation/provenance, never live data — a
        long-form measurement writeup, a domain note, or a recorded-but-
        currently-unconsumed value (e.g. ``planner._plant_gain``, a
        recorded plant-ID measurement no `_require()` call reads any
        more). ``extra="forbid"`` (132-016) is exactly right for catching
        a genuinely unrecognized or misspelled REAL field name, but would
        otherwise also reject every one of these documentation keys the
        moment they sit inside a group this generator's own schema
        validates strictly (Geometry/Motors/Drive/WheelControl/Planner/
        PlannerShaper/Otos/Estimator, and even the hand-declared host-only
        sections) — since none of them, by design, declares an
        ``Optional[str]`` field for a note nobody consumes.

        Stripping happens HERE, on the raw dict, before any nested
        ``BaseModel`` is constructed — a ``model_validator(mode="before")``
        on the ROOT model receives the whole not-yet-parsed JSON tree, so
        by the time pydantic descends into ``geometry``/``otos``/etc. the
        underscore keys are already gone from those nested dicts too, and
        every sub-model's own ``extra="forbid"`` never even sees them.
        This does NOT touch the JSON FILE on disk — the notes stay
        exactly where the migration script placed them, physically
        alongside the field they document; this only shrinks what
        pydantic is asked to validate.
        """
        if not isinstance(data, dict):
            return data

        def strip(obj):
            if isinstance(obj, dict):
                return {k: strip(v) for k, v in obj.items() if not k.startswith("_")}
            if isinstance(obj, list):
                return [strip(v) for v in obj]
            return obj

        return strip(data)

    @model_validator(mode="after")
    def _resolve_encoder_fields(self) -> "RobotConfig":
        if not self.encoders.has_encoders:
            return self
        w = self.wheels
        wd, tpr, tpm = w.wheel_diameter_mm, w.ticks_per_rev, w.ticks_per_mm
        present = sum(v is not None for v in (wd, tpr, tpm))

        if present == 3:
            assert wd and tpr and tpm
            expected = tpr / (math.pi * wd)
            if abs(expected - tpm) / tpm > 0.01:
                raise ValueError(
                    f"Encoder fields inconsistent: wheel_diameter_mm={wd}, "
                    f"ticks_per_rev={tpr}, ticks_per_mm={tpm} (given) vs "
                    f"{expected:.6f} (computed). Exceeds 1% tolerance."
                )
            self.mm_per_tick = 1.0 / tpm

        elif present == 2:
            if wd is None:
                assert tpr and tpm
                w.wheel_diameter_mm = tpr / (math.pi * tpm)
            elif tpr is None:
                assert tpm and wd
                w.ticks_per_rev = tpm * math.pi * wd
            else:
                assert wd and tpr
                w.ticks_per_mm = tpr / (math.pi * wd)
            if w.ticks_per_mm is not None:
                self.mm_per_tick = 1.0 / w.ticks_per_mm

        elif w.ticks_per_mm is not None:
            self.mm_per_tick = 1.0 / w.ticks_per_mm

        return self

    # ------------------------------------------------------------------
    # Convenience flat accessors (avoids updating all call sites)
    # ------------------------------------------------------------------

    @property
    def robot_name(self) -> str:
        return self.identity.robot_name

    @property
    def uid(self) -> str:
        return self.identity.uid

    @property
    def hardware_model(self) -> str:
        return self.identity.hardware_model

    @property
    def common_name(self) -> str:
        return self.identity.common_name

    @property
    def robot_tag_id(self) -> int:
        return self.vision.robot_tag_id

    # 132-020: ``tag_offset_mm`` (nested OffsetXYYaw) and ``motor_deadband``
    # are deliberately DROPPED, not ported. ``tag_offset_mm`` -- the
    # generated ``Vision`` group flattens this into
    # tag_offset_x/y/z/yaw (no nested-offset home left to point at); its
    # one caller (``src/tests/playfield/pose_fix_convergence.py``) is an
    # HITL playfield tool, not pytest-collected. ``motor_deadband`` sourced
    # from the OLD JSON's own confusingly-named top-level "drive" section
    # (motor_deadband/max_cmd/...), which robot_config.proto's own header
    # comment calls out as "read by no firmware code" and excludes
    # entirely -- its one caller (``robot_radio.nav.navigator.
    # _load_motor_deadband()``) already wraps the read in
    # ``try/except Exception: pass`` with a literal ``35`` fallback, so
    # this is a silent, harmless degrade, not a crash.

    @property
    def trackwidth(self) -> float:
        return self.geometry.trackwidth

    @property
    def has_gripper(self) -> bool:
        return self.gripper.has_gripper

    @property
    def gripper_offset_mm(self) -> Optional[OffsetXY]:
        return self.gripper.gripper_offset_mm

    @property
    def laser_port(self) -> Optional[int]:
        return self.peripherals.laser_port

    @property
    def device_announcement_name(self) -> str:
        return self.connection.device_announcement_name

    @property
    def serial_last_6(self) -> str:
        return self.connection.serial_last_6

    @property
    def has_encoders(self) -> bool:
        return self.encoders.has_encoders

    @property
    def otos_angular_scale(self) -> float:
        return self.otos.angular_scale

    @property
    def otos_angular_scalar(self) -> int:
        return max(-128, min(127, round((self.otos.angular_scale - 1.0) / 0.001)))

    @property
    def otos_linear_scale(self) -> float:
        return self.otos.linear_scale

    @property
    def otos_linear_scalar(self) -> int:
        return max(-128, min(127, round((self.otos.linear_scale - 1.0) / 0.001)))


